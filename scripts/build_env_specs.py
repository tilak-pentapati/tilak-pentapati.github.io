"""Write per-project environment specs pinned to the local conda envs.

For every project page this writes, next to its index.qmd:

  environment.yml     conda-forge spec: the interpreter (python / r-base) plus
                      only the packages the page imports, pinned to the versions
                      installed in the local env the committed _freeze/ was
                      rendered with.
  cran-packages.txt   (R only, when needed) packages that are not on conda-forge
                      at the pinned version, as `Package==version`; installed from
                      the CRAN archive by scripts/repro/install_cran.R.

and binder/environment.yml, the union of all of them (mybinder.org builds one
environment per repository).

The satellites page keeps its hand-maintained requirements.txt (used by the
nightly CI job), so it is skipped here.

Run (no conda run/activate; the env binaries are called directly):

  /Users/jay/anaconda3/envs/envs563/bin/python scripts/build_env_specs.py

Versions come from `conda list --json` for each env and, for R packages that
were installed from CRAN into the conda library, from packageVersion().
"""

import json
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CONDA = "/Users/jay/anaconda3/bin/conda"
PY_ENV = "/Users/jay/anaconda3/envs/envs563"
R_ENV = "/Users/jay/anaconda3/envs/r_env_gds"
RSCRIPT = f"{R_ENV}/bin/Rscript"

# Packages each page imports (import name -> conda-forge name where they differ).
# Quarto's Jupyter engine needs ipykernel/nbclient/nbformat/pyyaml; knitr pages
# need knitr + rmarkdown. Those are added to every page as the render toolchain.
PY_TOOLCHAIN = ["ipykernel", "nbclient", "nbformat", "pyyaml"]
R_TOOLCHAIN = ["knitr", "rmarkdown"]

# Pages left out on purpose (no reproducibility layer): their data is under a
# restrictive licence or they need an unpublished course package owned by others.
#   bd_gps (Microsoft Research GeoLife licence), StrokePredictionModel (Kaggle data,
#   licence unclear), GCH_census and aps_eda (ENVS450 course package and data).
PY_PROJECTS = {
    "SP500_comp": ["numpy", "pandas", "scikit-learn", "plotly", "ipython"],
    "retail_site_select": ["geopandas", "pyogrio", "numpy", "pandas", "matplotlib"],
    "stPopLCR": ["geopandas", "pyogrio", "rasterio", "shapely", "numpy", "pandas", "matplotlib"],
}

R_PROJECTS = {
    # The page library()s its whole packages_required vector, so all are needed to render.
    "airbnb_sf": ["tidycensus", "tigris", "tidyverse", "data.table", "sf", "tmap",
                  "tmaptools", "readr", "geojsonsf", "osmdata", "devtools", "logger",
                  "RColorBrewer", "classInt", "R.utils", "dplyr", "ggplot2", "viridis",
                  "raster", "terra", "exactextractr", "tidyterra", "tibble", "rosm",
                  "spdep", "cluster", "GGally", "tidyr", "gridExtra", "patchwork"],
    "se_m_airbnb": ["RColorBrewer", "arm", "dplyr", "ggplot2", "gridExtra", "gstat", "hexbin",
                    "kableExtra", "sf", "sp", "spatialreg", "spdep", "stringr", "tidyverse",
                    "tmap", "viridis"],
    "stm_covid": ["FRK", "MASS", "RColorBrewer", "car", "corrplot", "dplyr", "gghighlight",
                  "ggplot2", "gridExtra", "jtools", "kableExtra", "lme4", "lmtest", "lubridate",
                  "merTools", "sf", "sp", "spacetime", "spgwr", "tidyverse", "tmap", "viridis"],
}

# Not on conda-forge (checked with `CONDA_SUBDIR=linux-64 conda search -c conda-forge`):
# installed from the CRAN archive at the local version instead.
R_CRAN_ONLY = {"FRK", "spgwr", "tidyterra"}
# University of Liverpool ENVS450 course helper package (not published anywhere).
R_UNPUBLISHED = {"ENVS450"}

HEADER = """\
# {what} environment for {page}
# Generated by scripts/build_env_specs.py from the local `{env}` conda env
# (the env the committed _freeze/ was rendered with). Only the packages the
# page imports are listed, plus the Quarto render toolchain.
#   micromamba create -n {name} -f {rel}
# or, in the dev container / Binder: scripts/repro/setup-env.sh {proj_rel}
"""


def conda_list(prefix):
    out = subprocess.run([CONDA, "list", "-p", prefix, "--json"], check=True,
                         capture_output=True, text=True).stdout
    return {p["name"]: p for p in json.loads(out)}


def r_versions(pkgs):
    # packageDescription() keeps CRAN's spelling (4.4-1); packageVersion() gives 4.4.1.
    code = ("for (p in commandArgs(TRUE)) cat(p, packageDescription(p)$Version, '\\n');"
            "cat('R', paste(R.version$major, R.version$minor, sep='.'), '\\n')")
    out = subprocess.run([RSCRIPT, "-e", code, *pkgs], check=True,
                         capture_output=True, text=True).stdout
    return dict(line.split() for line in out.strip().splitlines())


def yaml_env(name, conda_deps, pip_deps, header):
    lines = [header, f"name: {name}", "channels:", "  - conda-forge", "dependencies:"]
    lines += [f"  - {d}" for d in conda_deps]
    if pip_deps:
        lines += ["  - pip", "  - pip:"] + [f"      - {d}" for d in pip_deps]
    return "\n".join(lines) + "\n"


def python_specs(pkgs_by_name):
    specs = {}
    py = pkgs_by_name["python"]["version"]
    for proj, imports in PY_PROJECTS.items():
        conda_deps, pip_deps = [f"python={py}"], []
        for name in imports + PY_TOOLCHAIN:
            p = pkgs_by_name[name]
            if p["channel"] == "pypi":
                pip_deps.append(f"{name}=={p['version']}")
            else:
                conda_deps.append(f"{name}={p['version']}")
        specs[proj] = (conda_deps, pip_deps)
    return specs


def r_specs(pkgs_by_name, rver):
    specs = {}
    for proj, imports in R_PROJECTS.items():
        conda_deps = [f"r-base={pkgs_by_name['r-base']['version']}"]
        cran, unpublished = [], []
        for name in imports + R_TOOLCHAIN:
            if name in R_UNPUBLISHED:
                unpublished.append(name)
            elif name in R_CRAN_ONLY:
                cran.append(f"{name}=={rver[name]}")
            else:
                cname = "r-" + name.lower()
                # conda-forge spells R versions with "_" for "-" (e.g. 1.1-3 -> 1.1_3).
                version = (pkgs_by_name[cname]["version"] if cname in pkgs_by_name
                           else rver[name].replace("-", "_"))
                conda_deps.append(f"{cname}={version}")
        if cran:
            conda_deps.append(f"r-remotes={pkgs_by_name['r-remotes']['version']}"
                              if "r-remotes" in pkgs_by_name else "r-remotes")
        specs[proj] = (conda_deps, cran, unpublished)
    return specs


def main():
    py_pkgs = conda_list(PY_ENV)
    r_pkgs = conda_list(R_ENV)
    all_r = sorted({p for v in R_PROJECTS.values() for p in v} - R_UNPUBLISHED)
    rver = r_versions(all_r)

    union_conda, union_pip, union_cran = {}, set(), set()

    for proj, (conda_deps, pip_deps) in python_specs(py_pkgs).items():
        d = ROOT / "projects" / "python" / proj
        rel = (d / "environment.yml").relative_to(ROOT)
        header = HEADER.format(what="Python", page=f"projects/python/{proj}/index.qmd",
                               env="envs563", name=proj.lower(), rel=rel,
                               proj_rel=d.relative_to(ROOT))
        (d / "environment.yml").write_text(yaml_env(proj.lower(), conda_deps, pip_deps, header))
        for dep in conda_deps:
            union_conda[dep.split("=")[0]] = dep
        union_pip.update(pip_deps)

    for proj, (conda_deps, cran, unpublished) in r_specs(r_pkgs, rver).items():
        d = ROOT / "projects" / "r" / proj
        rel = (d / "environment.yml").relative_to(ROOT)
        header = HEADER.format(what="R", page=f"projects/r/{proj}/index.qmd",
                               env="r_env_gds", name=proj.lower(), rel=rel,
                               proj_rel=d.relative_to(ROOT))
        if cran:
            header += "# Not on conda-forge; installed from the CRAN archive: cran-packages.txt\n"
        for name in unpublished:
            header += (f"# {name}: University of Liverpool ENVS450 course helper package"
                       " (unpublished); install it from the course materials.\n")
        (d / "environment.yml").write_text(yaml_env(proj.lower(), conda_deps, [], header))
        cran_file = d / "cran-packages.txt"
        if cran:
            cran_file.write_text(
                f"# CRAN packages for projects/r/{proj}/index.qmd that are not on conda-forge.\n"
                f"# Pinned to the local r_env_gds library (R {rver['R']}); installed by\n"
                "# scripts/repro/install_cran.R into the env built from environment.yml.\n"
                + "\n".join(cran) + "\n")
        elif cran_file.exists():
            cran_file.unlink()
        for dep in conda_deps:
            union_conda[dep.split("=")[0]] = dep
        union_cran.update(cran)

    # The satellites page's hand-maintained requirements.txt joins the Binder union.
    sat = ROOT / "projects" / "python" / "satellites_overhead" / "requirements.txt"
    for line in sat.read_text().splitlines():
        name = line.split("#")[0].split("==")[0].strip()
        if name:
            p = py_pkgs[name]
            if p["channel"] == "pypi":
                union_pip.add(f"{name}=={p['version']}")
            else:
                union_conda[name] = f"{name}={p['version']}"

    # Binder: one environment for every page. Interpreters first, then alphabetical.
    first = [union_conda.pop("python"), union_conda.pop("r-base")]
    binder_deps = first + [union_conda[k] for k in sorted(union_conda)]
    header = ("# mybinder.org environment: the union of every project's environment.yml\n"
              "# (generated by scripts/build_env_specs.py; do not edit by hand).\n"
              "# postBuild adds Quarto and the CRAN-only packages in cran-packages.txt.\n")
    (ROOT / "binder").mkdir(exist_ok=True)
    (ROOT / "binder" / "environment.yml").write_text(
        yaml_env("portfolio", binder_deps, sorted(union_pip), header))
    print(f"Wrote {len(PY_PROJECTS)} Python + {len(R_PROJECTS)} R specs and binder/environment.yml "
          f"(R {rver['R']}, Python {py_pkgs['python']['version']}).")


if __name__ == "__main__":
    main()
