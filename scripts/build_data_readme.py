"""Write data/README.md from each project's `reproduce:` metadata.

The same block drives the page's "Data availability" appendix
(assets/filters/summary-card.lua), so the two never drift. Run after editing
any projects/*/*/_metadata.yml:

  /Users/jay/anaconda3/envs/envs563/bin/python scripts/build_data_readme.py
"""

from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
SITE = "https://tilak-pentapati.github.io"

INTRO = """\
# Data

Raw datasets for the project pages live here, in `data/data_python/<project>/`
and `data/data_r/<project>/`. Most of it (about 1.2 GB, some under licences that
forbid redistribution) is **gitignored and not in the repository**: the
published site is rendered from the committed `_freeze/` results, so nobody
needs the data to build the site, only to re-run a page.

To re-run a page: fetch its data below into the expected path, build its
environment with `scripts/repro/setup-env.sh projects/<python|r>/<project>`,
then render it with the command that script prints (see `REPRODUCIBILITY.md`).

Each project page has the same information in its "Data availability" section.
This file is generated by `scripts/build_data_readme.py` from the `reproduce:`
block in each `projects/*/*/_metadata.yml`; edit those, not this file.
"""


def title_of(qmd):
    text = qmd.read_text().split("---", 2)[1]
    return yaml.safe_load(text)["title"]


def main():
    out = [INTRO]
    for meta_file in sorted(ROOT.glob("projects/*/*/_metadata.yml")):
        meta = yaml.safe_load(meta_file.read_text()) or {}
        repro = meta.get("reproduce")
        if not repro:
            continue
        d = meta_file.parent
        rel = d.relative_to(ROOT).as_posix()
        out.append(f"## {title_of(d / 'index.qmd')}\n")
        out.append(f"Page: <{SITE}/{rel}/> · Source: `{rel}/index.qmd` · "
                   f"Environment: [`{rel}/{repro['env']}`](../{rel}/{repro['env']})\n")
        for src in repro.get("data", []):
            out.append(f"- **[{src['name']}]({src['url']})**")
            out.append(f"  - Licence: {src['licence']}")
            out.append(f"  - How to get it: {src['fetch']}")
            out.append(f"  - Expected path: {src['path']}")
        if repro.get("note"):
            out.append(f"\n{repro['note']}")
        out.append("")
    (ROOT / "data" / "README.md").write_text("\n".join(out))
    print("Wrote data/README.md")


if __name__ == "__main__":
    main()
