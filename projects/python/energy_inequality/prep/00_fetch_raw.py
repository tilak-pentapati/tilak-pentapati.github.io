"""Download any missing raw file listed in sources.py, record hashes, and write SOURCES.md.

    python -I 00_fetch_raw.py            # verify existing files, download missing ones, write SOURCES.md
    python -I 00_fetch_raw.py --offline  # never touch the network; just verify and write SOURCES.md

Files under superseded_local/ are local copies of superseded releases that are no
longer hosted; set ENERGY_LOCAL_COPIES to the folder holding them to restore them.
"""
import hashlib
import os
import shutil
import sys
import urllib.request
from pathlib import Path

sys.dont_write_bytecode = True  # keep __pycache__ out of the repo
sys.path.insert(0, str(Path(__file__).resolve().parent))
from _common import DATA, RAW, log  # noqa: E402
from sources import SOURCES  # noqa: E402

UA = "Mozilla/5.0 (energy-inequality data prep; contact via github.com/tilak-pentapati)"
ORIGINALS = Path(os.environ.get("ENERGY_LOCAL_COPIES", "superseded_local_copies"))


def sha256(p: Path) -> str:
    h = hashlib.sha256()
    with open(p, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def fetch(src: dict, offline: bool) -> None:
    dest = RAW / src["path"]
    if dest.exists():
        return
    dest.parent.mkdir(parents=True, exist_ok=True)
    if src["path"].startswith("superseded_local/"):
        orig = ORIGINALS / dest.name
        if orig.exists():
            shutil.copy2(orig, dest)
            log(f"copied {orig} -> {dest}")
            return
        raise FileNotFoundError(f"{dest} missing and original {orig} not found")
    if offline:
        raise FileNotFoundError(f"{dest} missing (offline mode)")
    log(f"downloading {src['url']}")
    req = urllib.request.Request(src["url"], headers={"User-Agent": UA})
    with urllib.request.urlopen(req, timeout=600) as r, open(dest, "wb") as fh:
        shutil.copyfileobj(r, fh)


def write_sources_md(rows: list[dict]) -> Path:
    out = DATA / "SOURCES.md"
    lines = [
        "# Energy inequality project: raw data sources",
        "",
        "Generated by `projects/python/energy_inequality/prep/00_fetch_raw.py` from `sources.py`.",
        "All files live under `data/data_python/energy_inequality/raw/` (gitignored via `data/data_python/`).",
        "Every source is an official UK statistics publisher (DESNZ/gov.uk, ONS, ONS Open Geography Portal, Nomis, MHCLG, Welsh Government).",
        "",
        "Licence summary: all files are Crown copyright under the Open Government Licence v3.0",
        "(<https://www.nationalarchives.gov.uk/doc/open-government-licence/version/3/>). ONS boundary and lookup",
        "products additionally require the attribution: *Source: Office for National Statistics licensed under the Open",
        "Government Licence v.3.0. Contains OS data © Crown copyright and database right [year]*.",
        "",
        f"Downloaded/verified: 2026-10-26. Files: {len(rows)}.",
        "",
    ]
    group = None
    for r in rows:
        if r["group"] != group:
            group = r["group"]
            lines += [f"## {group}", ""]
        lines += [
            f"### `raw/{r['path']}`",
            "",
            f"- **What:** {r['title']}",
            f"- **Publisher:** {r['publisher']}",
            f"- **Release date:** {r['released']}",
            f"- **Licence:** {r['licence']}",
            f"- **Source URL:** {r['url']}",
            f"- **Landing page:** {r['page']}",
            f"- **Size / SHA-256:** {r['size']:,} bytes / `{r['sha256']}`",
            "",
        ]
    out.write_text("\n".join(lines))
    return out


def main() -> None:
    offline = "--offline" in sys.argv
    rows = []
    for src in SOURCES:
        fetch(src, offline)
        p = RAW / src["path"]
        rows.append({**src, "size": p.stat().st_size, "sha256": sha256(p)})
    listed = {RAW / s["path"] for s in SOURCES}
    extra = [p for p in RAW.rglob("*") if p.is_file() and p not in listed and p.name != ".DS_Store"]
    if extra:
        log("WARNING: raw files not in the manifest: " + ", ".join(str(p.relative_to(RAW)) for p in extra))
    log(f"verified {len(rows)} raw files; wrote {write_sources_md(rows)}")


if __name__ == "__main__":
    main()
